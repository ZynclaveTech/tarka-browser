"""Writes .github/workflows/windows.yml, Tark's Windows build on GitHub's
free runners (W2): python3 windows/ci/gen_workflow.py

A Chromium build takes far longer than one job may run (6 hours), so it runs
in stages, as upstream ungoogled-chromium-windows's workflow does (BSD-3):
each stage builds for 3.5 hours (build.py --ci) and hands the source tree to
the next as an artifact, until one finishes, packages Tark and checks it
(windows/ci/verify.ps1). A first job builds ONNX Runtime with the static C
runtime (windows/ci/build_onnxruntime.ps1), cached between runs.

A failed run can be resumed rather than rebuilt: run the workflow by hand
with resume_run (the failed run's id) and resume_stage (the stage that
failed). That stage takes the tree the stage before it handed on (kept
3 days), applies windows/ci/resume.patch to it if there is one (the fix,
since build.py --ci does not re-patch a tree it is handed), and builds on.

The finishing stage keeps Tark (the zip and installer) and the test programs
as artifacts, and a separate job checks them (windows/ci/verify.ps1). Run the
workflow by hand with verify_run (a finished run's id) to check that run's
build again, with changed checks, without building.
"""

import pathlib

STAGES = 16
CHECKOUT = 'actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1  # v7.0.1'
SETUP_PYTHON = 'actions/setup-python@5fda3b95a4ea91299a34e894583c3862153e4b97  # v7.0.0'
CACHE = 'actions/cache@55cc8345863c7cc4c66a329aec7e433d2d1c52a9  # v6.1.0'
UPLOAD = 'actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9  # v7.0.2'
DOWNLOAD = 'actions/download-artifact@9000827ccba6bdab643e8b6fd33ac0654aef8333  # v8.0.2'

HEADER = f'''# Generated by windows/ci/gen_workflow.py; edit that, then rerun it.
#
# Tark for Windows x64 (W2) on GitHub's free runners: ONNX Runtime first,
# then up to {STAGES} stages of the Chromium build, each handing the source
# tree to the next, as upstream ungoogled-chromium-windows builds (BSD-3).
name: Windows build

on:
  workflow_dispatch:
    inputs:
      resume_run:
        description: Resume this failed run (its id); empty builds from the start
        type: string
        default: ''
      resume_stage:
        description: The stage to resume at, with the tree the stage before it handed on
        type: number
        default: 1
      verify_run:
        description: Only check this finished run's build again (its id); builds nothing
        type: string
        default: ''
  push:
    branches:
      - feat/w2-windows-parity

permissions:
  contents: read
  # Downloading the tree from the run being resumed.
  actions: read

concurrency:
  group: windows-${{{{ github.ref }}}}
  # A push does not cancel a running build (a day and a half); cancel by hand.
  cancel-in-progress: false

jobs:
  onnxruntime:
    name: ONNX Runtime (static C runtime)
    if: ${{{{ inputs.verify_run == '' }}}}
    runs-on: windows-2022
    timeout-minutes: 300
    steps:
      - name: Line endings as committed
        run: |
          git config --global core.autocrlf false
          git config --global core.eol lf
      - uses: {CHECKOUT}
        with:
          persist-credentials: false
      - uses: {SETUP_PYTHON}
        with:
          python-version: '3.12'
      - name: Restore an earlier build
        id: cache
        uses: {CACHE}
        with:
          path: C:\\ort-out
          key: onnxruntime-1.31.0-402979a-static-${{{{ hashFiles('windows/ci/build_onnxruntime.ps1', 'windows/ci/onnxruntime-patches/*') }}}}
      - name: Build ONNX Runtime 1.31.0
        if: steps.cache.outputs.cache-hit != 'true'
        shell: pwsh
        run: windows\\ci\\build_onnxruntime.ps1 -Out C:\\ort-out
      - name: Check it needs no C runtime
        shell: pwsh
        run: windows\\ci\\build_onnxruntime.ps1 -Out C:\\ort-out -CheckOnly
      - uses: {UPLOAD}
        with:
          name: onnxruntime-win-x64
          path: C:\\ort-out
          retention-days: 7
'''

STAGE = '''
  build-{n}:
    name: Build, stage {n}
    needs: {needs}
{cond}    runs-on: windows-2022
    timeout-minutes: 355
    outputs:
      finished: ${{{{ steps.build.outputs.finished }}}}
    steps:
      - name: Line endings as committed
        run: |
          git config --global core.autocrlf false
          git config --global core.eol lf
      - uses: {checkout}
        with:
          submodules: true
          persist-credentials: false
      - uses: {setup_python}
        with:
          python-version: '3.12'
      - name: Windows SDK 10.0.28000
        shell: pwsh
        run: |
          if (Test-Path 'C:\\Program Files (x86)\\Windows Kits\\10\\Include\\10.0.28000.0') {{ exit 0 }}
          $installer = "$env:TEMP\\winsdksetup.exe"
          Invoke-WebRequest -UseBasicParsing -Uri 'https://download.microsoft.com/download/38ab8f6d-3676-4860-ae84-3361308b9d7f/KIT_BUNDLE_WINDOWSSDK_MEDIACREATION/winsdksetup.exe' -OutFile $installer
          $features = '/features OptionId.DesktopCPPx64 OptionId.DesktopCPPx86 OptionId.DesktopCPPArm64 OptionId.WindowsDesktopDebuggers OptionId.UWPCPP OptionId.SigningTools /q /norestart /ceip off'
          $proc = Start-Process -FilePath $installer -ArgumentList $features -PassThru -Wait
          if ($proc.ExitCode -ne 0) {{ throw "winsdksetup.exe failed with code $($proc.ExitCode)" }}
          if (-not (Test-Path 'C:\\Program Files (x86)\\Windows Kits\\10\\Include\\10.0.28000.0')) {{ throw 'SDK 10.0.28000.0 not installed' }}
      - name: ONNX Runtime
        uses: {download}
        with:
          name: onnxruntime-win-x64
          path: C:\\ort
      - name: Work folder
        shell: pwsh
        run: python windows\\prepare_workdir.py $env:GITHUB_WORKSPACE C:\\tw
{resume}      - name: Build
        id: build
        shell: pwsh
        working-directory: C:\\tw
        env:
          TARK_ORT_DIR: C:\\ort
          TARK_NINJA_HOURS: '{hours}'
        run: |
          python -m pip install --disable-pip-version-check httplib2==0.22.0 clang==21.1.7
          python build.py --ci --tarball -j 3
          $code = $LASTEXITCODE
          if ($code -eq 0) {{ 'finished=true' >> $env:GITHUB_OUTPUT }}
          elseif ($code -eq 124) {{ 'finished=false' >> $env:GITHUB_OUTPUT; exit 0 }}
          else {{ exit $code }}
      - name: Pack the tree for the next stage
        if: steps.build.outputs.finished == 'false'
        shell: pwsh
        run: |
          # 7-Zip exits 1 for warnings: the Chromium tarball's symbolic links
          # (test data) cannot be read on Windows and are not needed. Volumes
          # of 2 GB: one 8 GB file in an artifact failed to download.
          7z a -tzip -v2000m C:\\tw\\tree.zip C:\\tw\\build\\src -mx=3 -mtc=on
          if ($LASTEXITCODE -ge 2) {{ exit $LASTEXITCODE }}
          exit 0
      - name: Hand the tree on
        if: steps.build.outputs.finished == 'false'
        uses: {upload}
        with:
          name: build-tree
          path: C:\\tw\\tree.zip.*
          compression-level: 0
          retention-days: 3
          overwrite: true
      - name: Upload Tark for Windows
        if: steps.build.outputs.finished == 'true'
        uses: {upload}
        with:
          name: tark-windows-x64
          path: C:\\tw\\build\\Tark-*
          compression-level: 0
          retention-days: 14
      - name: Gather the test programs
        if: steps.build.outputs.finished == 'true'
        shell: pwsh
        run: |
          # The unit tests, what they load, and their symbols, so the checks
          # can run again later without a build (verify_run).
          $out = 'C:\\tw\\build\\src\\out\\Default'
          $kit = 'C:\\tw\\tests'
          New-Item -ItemType Directory -Force $kit | Out-Null
          foreach ($f in 'tark_captions_unittests.exe', 'tark_speech_unittests.exe', 'icudtl.dat', 'onnxruntime.dll') {{
            Copy-Item "$out\\$f" $kit
          }}
          Get-ChildItem "$out\\tark_*_unittests*.pdb" -ErrorAction SilentlyContinue | Copy-Item -Destination $kit
          Get-ChildItem "$out\\*.dll" | Where-Object Name -ne 'chrome.dll' | Copy-Item -Destination $kit
          Get-ChildItem $kit | Format-Table Name, Length -AutoSize | Out-String -Width 200
      - name: Keep the test programs
        if: steps.build.outputs.finished == 'true'
        uses: {upload}
        with:
          name: tark-windows-tests
          path: C:\\tw\\tests
          retention-days: 14
'''

RESUME = '''      - name: The tree from the last stage
        if: ${{{{ !(inputs.resume_run != '' && inputs.resume_stage == {n}) }}}}
        uses: {download}
        with:
          name: build-tree
          path: C:\\tw\\build
      - name: The tree from the run being resumed
        if: ${{{{ inputs.resume_run != '' && inputs.resume_stage == {n} }}}}
        uses: {download}
        with:
          name: build-tree
          path: C:\\tw\\build
          run-id: ${{{{ inputs.resume_run }}}}
          github-token: ${{{{ github.token }}}}
      - name: Unpack the tree
        shell: pwsh
        run: |
          7z x C:\\tw\\build\\tree.zip.001 -oC:\\tw\\build -y
          if ($LASTEXITCODE -ge 2) {{ exit $LASTEXITCODE }}
          Remove-Item C:\\tw\\build\\tree.zip.*
          exit 0
      - name: The fix for the run being resumed
        if: ${{{{ inputs.resume_run != '' && inputs.resume_stage == {n} && hashFiles('windows/ci/resume.patch') != '' }}}}
        shell: pwsh
        working-directory: C:\\tw\\build\\src
        run: |
          git apply -p1 --verbose "$env:GITHUB_WORKSPACE\\windows\\ci\\resume.patch"
          if ($LASTEXITCODE -ne 0) {{ exit $LASTEXITCODE }}
'''

COMPLETE = '''
  complete:
    name: Finished
    needs: [{needs}]
    if: ${{{{ always() && inputs.verify_run == '' }}}}
    runs-on: ubuntu-24.04
    steps:
      - name: A stage finished the build
        env:
          FINISHED: ${{{{ contains(toJSON(needs.*.outputs.finished), 'true') }}}}
        run: |
          if [ "$FINISHED" != "true" ]; then
            echo "No stage finished the build."
            exit 1
          fi

  verify:
    name: Check the build
    needs: [complete]
    if: ${{{{ !cancelled() && (needs.complete.result == 'success' || inputs.verify_run != '') }}}}
    runs-on: windows-2022
    timeout-minutes: 90
    steps:
      - name: Line endings as committed
        run: |
          git config --global core.autocrlf false
          git config --global core.eol lf
      - uses: {checkout}
        with:
          persist-credentials: false
      - name: Tark for Windows
        uses: {download}
        with:
          name: tark-windows-x64
          path: C:\\tw\\build
          run-id: ${{{{ inputs.verify_run || github.run_id }}}}
          github-token: ${{{{ github.token }}}}
      - name: The test programs
        uses: {download}
        with:
          name: tark-windows-tests
          path: C:\\tw\\tests
          run-id: ${{{{ inputs.verify_run || github.run_id }}}}
          github-token: ${{{{ github.token }}}}
      - name: Check the build
        shell: pwsh
        run: windows\\ci\\verify.ps1 -Work C:\\tw -Tests C:\\tw\\tests -Report C:\\tw\\verify
      - name: Upload the checks
        if: always()
        uses: {upload}
        with:
          name: tark-windows-checks
          path: C:\\tw\\verify
          retention-days: 14
'''


def main():
    text = HEADER
    for n in range(1, STAGES + 1):
        if n == 1:
            prev = 'onnxruntime'
            cond = ("    if: ${{ !(inputs.resume_run != '' && inputs.resume_stage > 1) }}\n")
        else:
            prev = f'[onnxruntime, build-{n - 1}]'
            cond = ("    if: >-\n"
                    "      ${{ !cancelled() && needs.onnxruntime.result == 'success' && (\n"
                    f"      (needs.build-{n - 1}.result == 'success' && needs.build-{n - 1}.outputs.finished == 'false') ||\n"
                    f"      (inputs.resume_run != '' && inputs.resume_stage == {n})) }}}}\n")
        resume = '' if n == 1 else RESUME.format(download=DOWNLOAD, n=n)
        text += STAGE.format(n=n, needs=prev, cond=cond, resume=resume, checkout=CHECKOUT,
                             hours='3.5',
                             setup_python=SETUP_PYTHON, download=DOWNLOAD, upload=UPLOAD)
    text += COMPLETE.format(needs=', '.join(f'build-{n}' for n in range(1, STAGES + 1)),
                            checkout=CHECKOUT, download=DOWNLOAD, upload=UPLOAD)
    out = pathlib.Path(__file__).resolve().parents[2] / '.github' / 'workflows' / 'windows.yml'
    out.write_text(text, encoding='utf-8')
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
