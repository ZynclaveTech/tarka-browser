"""The live captions model manifest (D4 Phase 4).

    captions_manifest.py MODELS_DIR OUT_CC
    captions_manifest.py --check MODELS_DIR MANIFEST_CC

Writes components/tark_captions/model_manifest.cc: for each download unit
(Indian captions, translation into English, translation into Indian
languages), every file's path relative to the models folder, its size and
its SHA-256. Tark verifies each downloaded file against this table, so the
table must come from exactly the files published on gettarka.com. --check
exits non-zero when MODELS_DIR does not match MANIFEST_CC (run it before
publishing).
"""
import hashlib
import os
import re
import sys

CAPTIONS = ('encoder.int8.onnx', 'ctc_decoder.onnx', 'vocab.json', 'language_masks.json',
            'window.f32', 'mel_fb.f32', 'silero_vad.onnx')
TRANSLATION = ('encoder.int8.onnx', 'decoder_step.int8.onnx', 'model.SRC', 'dict.SRC.json',
               'dict.TGT.json', 'config.json', 'LICENSE')
UNITS = (
    ('kCaptions', 'captions', 'kCaptionsFiles', [p for p in CAPTIONS]),
    ('kToEnglish', 'to_english', 'kToEnglishFiles', [f'it2_indic_en/{n}' for n in TRANSLATION]),
    ('kFromEnglish', 'from_english', 'kFromEnglishFiles',
     [f'it2_en_indic/{n}' for n in TRANSLATION]),
)


def describe(models, path):
    digest = hashlib.sha256()
    with open(os.path.join(models, path), 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            digest.update(block)
    return os.path.getsize(os.path.join(models, path)), digest.hexdigest()


def generate(models):
    out = ['// Copyright 2026 The Tark Authors',
           '// Use of this source code is governed by a BSD-style license that can be',
           '// found in the LICENSE file.',
           '',
           '// Generated by utils/captions_manifest.py from the models Tark was tested',
           '// with and publishes on gettarka.com. Do not edit.',
           '',
           '#include "components/tark_captions/model_manifest.h"',
           '',
           'namespace tark_captions {',
           'namespace {',
           '']
    for _, _, array, paths in UNITS:
        out.append(f'constexpr ModelFile {array}[] = {{')
        for path in sorted(paths):
            size, sha = describe(models, path)
            out.append(f'    {{"{path}", {size}, "{sha}"}},')
        out.extend(['};', ''])
    out.append('constexpr ModelUnitInfo kUnits[] = {')
    for enum, unit_id, array, _ in UNITS:
        out.append(f'    {{ModelUnit::{enum}, "{unit_id}", {array}}},')
    out.extend(['};', '', '}  // namespace', '',
                'base::span<const ModelUnitInfo> ModelManifest() {', '  return kUnits;', '}', '',
                '}  // namespace tark_captions', ''])
    return '\n'.join(out)


def check(models, manifest_cc):
    with open(manifest_cc, encoding='utf-8') as f:
        rows = re.findall(r'\{"([^"]+)", (\d+), "([0-9a-f]{64})"\}', f.read())
    bad = [path for path, size, sha in rows
           if not os.path.isfile(os.path.join(models, path))
           or describe(models, path) != (int(size), sha)]
    for path in bad:
        print(f'differs: {path}', file=sys.stderr)
    return 1 if bad or not rows else 0


def main():
    if len(sys.argv) == 4 and sys.argv[1] == '--check':
        sys.exit(check(sys.argv[2], sys.argv[3]))
    if len(sys.argv) == 3:
        with open(sys.argv[2], 'w', encoding='utf-8') as f:
            f.write(generate(sys.argv[1]))
        return
    sys.exit(__doc__.split('\n\n')[1])


if __name__ == '__main__':
    main()
