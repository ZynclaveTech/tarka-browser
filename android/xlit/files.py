"""The IndicXlit files Tark for Android downloads (A3, spec §5).

    files.py build WORDS_DIR ENGLISH MODEL OUT_DIR
    files.py header FILES_JSON OUT.inc

build: the model as is, and one TXLW v1 file per language,
xlit-words-<tag>.bin, holding that language's list and the common-English
list (utils/xlit_wordlist.py pack), so a phone downloads only its own
languages. files.json pins each file's size and sha256.

header: files.json as C++ initialiser rows, {"name", size, "sha256"},
compiled into the APK (chrome/browser/tark_xlit/xlit_files.inc): a
downloaded file that does not match is deleted.
"""

import hashlib
import json
import pathlib
import re
import shutil
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / 'utils'))
import xlit_wordlist  # noqa: E402

MODEL = 'xlit-model.bin'


def build(words_dir, english, model, out_dir):
    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(model, out / MODEL)
    for path in sorted(pathlib.Path(words_dir).iterdir()):
        m = re.fullmatch(r'([a-z]+)\.tsv(\.xz)?', path.name)
        if not m:
            continue
        with tempfile.TemporaryDirectory() as one:
            shutil.copyfile(path, pathlib.Path(one) / path.name)
            xlit_wordlist.pack(one, str(english), str(out / f'xlit-words-{m.group(1)}.bin'))
    table = {}
    for path in sorted(out.glob('*.bin')):
        data = path.read_bytes()
        table[path.name] = {'size': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
    (out / 'files.json').write_text(json.dumps(table, indent=1, sort_keys=True) + '\n')
    return table


def header(files_json, out_inc):
    table = json.loads(pathlib.Path(files_json).read_text())
    rows = [f'{{"{name}", {e["size"]}, "{e["sha256"]}"}},' for name, e in sorted(table.items())]
    pathlib.Path(out_inc).write_text(
        '// Generated by android/xlit/files.py from files.json. Do not edit.\n'
        + '\n'.join(rows) + '\n')


def main(argv):
    if len(argv) == 6 and argv[1] == 'build':
        build(*argv[2:6])
    elif len(argv) == 4 and argv[1] == 'header':
        header(*argv[2:4])
    else:
        print(__doc__, file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
